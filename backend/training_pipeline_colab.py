    # ============================================================
    # 5. KIỂM TRA VÀ CHỌN 2.000 ẢNH YOUTUBE
    # ============================================================

    IMAGE_EXTS = (".jpg", ".jpeg", ".png", ".webp")

    with zipfile.ZipFile(NEW_ZIP, "r") as zf:
        members = [
            name for name in zf.namelist()
            if name.lower().endswith(IMAGE_EXTS)
            and not name.endswith("/")
        ]

        print(f"\nSố ảnh tìm thấy trong ZIP YouTube: {len(members):,}")

        if len(members) < 2000:
            raise ValueError("ZIP không đủ 2.000 ảnh.")

        # Chọn ngẫu nhiên 2.000 ảnh, cố định kết quả bằng seed
        selected_members = random.sample(members, 2000)

        # Kiểm tra ảnh trước khi sao chép
        for i, member in enumerate(selected_members):
            image_bytes = zf.read(member)

            try:
                with Image.open(io.BytesIO(image_bytes)) as img:
                    img.verify()
            except Exception as e:
                raise ValueError(
                    f"Ảnh YouTube bị lỗi: {member}"
                ) from e

        print("Đã kiểm tra hợp lệ 2.000 ảnh mới.")

        # ========================================================
