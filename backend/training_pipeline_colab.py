# FFT & Frequency Feature Extraction
_FREQ_GEOM = {}

def _freq_geom(h, w):
    """Tính trước và cache các mask bán kính đồng tâm cho ảnh (h, w)."""
    key = (h, w)
    if key not in _FREQ_GEOM:
        cy, cx = h // 2, w // 2
        y, x = np.ogrid[:h, :w]
        r = np.sqrt((x - cx)**2 + (y - cy)**2).astype(int)
        max_r = min(cy, cx)
        bin_size = max_r / 48
        _FREQ_GEOM[key] = [
            np.flatnonzero(((r >= i * bin_size) & (r < (i + 1) * bin_size)).ravel())
            for i in range(48)
        ]
    return _FREQ_GEOM[key]

def extract_frequency_features(img_pil):
    """
    Trích xuất vector 64 chiều:
    - 48 chiều: Phổ năng lượng xuyên tâm 2D-FFT (Radial profile)
    - 16 chiều: Thống kê nhiễu từ bộ lọc SRM và biên độ phổ
    """
    img_gray = np.array(img_pil.convert('L'), dtype=np.float32)
    h, w = img_gray.shape

    # 2D-FFT và phổ biên độ
    mag_spec = np.log(np.abs(np.fft.fftshift(np.fft.fft2(img_gray))) + 1e-8)
    cy, cx = h // 2, w // 2
    flat = mag_spec.ravel()

    # 48 bin phổ xuyên tâm
    radial_prof = np.zeros(48, dtype=np.float32)
    for i, ix in enumerate(_freq_geom(h, w)):
        if ix.size:
            radial_prof[i] = flat[ix].mean()
    radial_prof = (radial_prof - radial_prof.mean()) / (radial_prof.std() + 1e-8)

    # Lọc nhiễu SRM
    srm_kernel = np.array([[0, 1, 0], [1, -4, 1], [0, 1, 0]], dtype=np.float32)
    noise_res = cv2.filter2D(img_gray, -1, srm_kernel)

    # Thống kê phân vị & biên độ
    q = np.percentile(noise_res, [10, 25, 50, 75, 90])
    p95 = np.percentile(mag_spec, 95)
    noise_stats = np.array([
        noise_res.mean(), noise_res.std(), q[0], q[1], q[2], q[3], q[4], np.var(noise_res),
        mag_spec[:cy//2, :cx//2].mean(), mag_spec[cy//2:, :cx//2].mean(),
        mag_spec[:cy//2, cx//2:].mean(), mag_spec[cy//2:, cx//2:].mean(),
        mag_spec[cy-10:cy+10, cx-10:cx+10].mean(),
        np.std(mag_spec),
        np.mean(mag_spec > p95),
        np.sum(mag_spec > (mag_spec.mean() + 2 * mag_spec.std())) / (h * w)
    ], dtype=np.float32)

    return np.concatenate([radial_prof, noise_stats])

